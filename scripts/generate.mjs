// Regenerates src/schema.ts from openapi/openapi.yaml.
//   node scripts/generate.mjs           regenerate from the vendored contract
//   node scripts/generate.mjs --fetch   download the live contract first
//   node scripts/generate.mjs --check   fail if src/schema.ts is out of date
// Descriptions are dropped from the generated types: the API reference at
// https://purrkey.app/docs is the documentation of record.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parse, stringify } from "yaml";

const CONTRACT_URL = "https://purrkey.app/docs/openapi.yaml";
const contractPath = "openapi/openapi.yaml";
const schemaPath = "src/schema.ts";

if (process.argv.includes("--fetch")) {
  const response = await fetch(CONTRACT_URL);
  if (!response.ok) throw new Error(`GET ${CONTRACT_URL} returned ${response.status}`);
  writeFileSync(contractPath, await response.text());
}

const ANNOTATIONS = new Set(["description", "summary", "example"]);
// Drops human-readable annotations. Keys under `properties` are field names
// (Price has a real `description` field), so they are always kept.
const strip = (node, isProperties = false) => {
  if (Array.isArray(node)) return node.map((item) => strip(item));
  if (!node || typeof node !== "object") return node;
  return Object.fromEntries(
    Object.entries(node)
      .filter(([key]) => isProperties || !ANNOTATIONS.has(key))
      .map(([key, value]) => [key, strip(value, !isProperties && key === "properties")]),
  );
};

const work = mkdtempSync(join(tmpdir(), "purrkey-openapi-"));
const stripped = join(work, "openapi.yaml");
const generated = join(work, "schema.ts");
writeFileSync(stripped, stringify(strip(parse(readFileSync(contractPath, "utf8")))));
execFileSync("npx", ["openapi-typescript", stripped, "-o", generated], { stdio: "ignore" });
const output = `// Generated by scripts/generate.mjs from openapi/openapi.yaml. Do not edit.\n${readFileSync(generated, "utf8")}`;

if (process.argv.includes("--check")) {
  if (readFileSync(schemaPath, "utf8") !== output) {
    console.error("src/schema.ts is out of date. Run npm run generate.");
    process.exit(1);
  }
  console.log("src/schema.ts is up to date");
} else {
  writeFileSync(schemaPath, output);
  console.log(`Wrote ${schemaPath}`);
}
